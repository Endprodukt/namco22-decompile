#!/usr/bin/env python3
"""c71_embed.py -- turn the C71 DSP BIOS (c71.bin, 8 KB, MAME's `namcoc71` set) into engine/c25/c71_bios.inc, so no game needs the file (or namcoc71.zip) any more.

    python3 tools/gen/c71_embed.py /path/to/c71.bin             write engine/c25/c71_bios.inc (only for the known-good dump)
    python3 tools/gen/c71_embed.py --check /path/to/c71.bin     is the built-in BIOS identical to this file?

The BIOS is a PROGRAM of the board (a TMS320C25 mask ROM): the DSP's boot code and its tables. It is the same file in every System 22 / Super 22 game
(Prop Cycle, Rave Racer, Tokyo Wars, Dirt Dash: one MD5). The games run its translation (gen/<game>_c25.c, made at build time by tools/gen/c25_translate.py) and need
its words in the DSP's program memory for the data reads and the translation's own consistency check; both now come from the built-in copy.
The .inc is 4096 big-endian 16-bit words, `0xWWWW,` eight to a line, included by engine/c25/c71_bios.c and read by c25_translate.py."""
import hashlib, os, sys, zlib

MD5 = "223914888d9be9ffe07952d9aa4c4107"      # MAME namcoc71: c71.bin, CRC32 47c623ab
CRC = 0x47c623ab
HERE = os.path.dirname(os.path.abspath(__file__))
INC = os.path.join(os.path.dirname(os.path.dirname(HERE)), "engine", "c25", "c71_bios.inc")

def words_of_inc(path=INC):
    import re
    return [int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{4})", open(path).read())]

def main():
    args = sys.argv[1:]
    check = bool(args) and args[0] == "--check"
    if check: args = args[1:]
    if len(args) != 1:
        print(__doc__.strip()); return 2
    data = open(os.path.expanduser(args[0]), "rb").read()
    if len(data) != 0x2000 or hashlib.md5(data).hexdigest() != MD5 or zlib.crc32(data) != CRC:
        print(f"c71_embed: {args[0]} is not MAME's c71.bin (md5 {hashlib.md5(data).hexdigest()}, {len(data)} bytes; expected {MD5}, 8192 bytes)"); return 1
    words = [(data[2 * i] << 8) | data[2 * i + 1] for i in range(len(data) // 2)]
    if check:
        same = words_of_inc() == words
        print("built-in BIOS %s %s" % ("IDENTICAL to" if same else "DIFFERS from", args[0])); return 0 if same else 1
    lines = ["/* GENERATED by tools/gen/c71_embed.py -- do not edit. The C71 DSP BIOS (MAME namcoc71 c71.bin, CRC32 47c623ab): 4096 16-bit words for program memory 0. */"]
    for i in range(0, len(words), 8):
        lines.append(" ".join("0x%04X," % w for w in words[i:i + 8]))
    open(INC, "w").write("\n".join(lines) + "\n")
    print(f"wrote {INC}: {len(words)} words"); return 0

sys.exit(main())
